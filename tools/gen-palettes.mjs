import { argbFromHex, Hct, SchemeTonalSpot, MaterialDynamicColors as M, Blend, TonalPalette } from '@material/material-color-utilities';

const seeds = { slate: '#5E7FA8', sage: '#6F8F7A', teal: '#5B8E8E', sand: '#A08F72', rose: '#A87A80' };
const courseHues = ['#8E7CC3', '#6F9BD1', '#6FAE8C', '#D0A85C', '#C97C7C', '#6FB3B8', '#A88FB0', '#9AA16A'];
const roles = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant', 'surfaceTint',
  'inverseSurface', 'inverseOnSurface', 'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim', 'surfaceBright', 'surfaceContainer', 'surfaceContainerHigh',
  'surfaceContainerHighest', 'surfaceContainerLow', 'surfaceContainerLowest', 'surfaceDim'];

const hex = (argb) => '0x' + (argb >>> 0).toString(16).toUpperCase().padStart(8, '0');
const scheme = (seed, dark) => {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
  const fn = dark ? 'darkColorScheme' : 'lightColorScheme';
  return `${fn}(\n${roles.map((r) => `            ${r} = Color(${hex(M[r].getArgb(s))}),`).join('\n')}\n        )`;
};
// Soft course colours: harmonised to the seed, chroma capped at 24. Pairs of (container, onContainer).
const course = (seed, dark) => courseHues.map((h) => {
  const hct = Hct.fromInt(Blend.harmonize(argbFromHex(h), argbFromHex(seed)));
  const p = TonalPalette.fromHueAndChroma(hct.hue, Math.min(hct.chroma, 24));
  return `Color(${hex(p.tone(dark ? 30 : 90))}) to Color(${hex(p.tone(dark ? 90 : 10))})`;
}).join(', ');

